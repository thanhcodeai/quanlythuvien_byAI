CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, username VARCHAR(64) NOT NULL UNIQUE,
 full_name VARCHAR(150) NOT NULL, email VARCHAR(254) NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'USER', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CHECK(role IN ('USER','ADMIN'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS books (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, book_code VARCHAR(50) NOT NULL UNIQUE,
 title VARCHAR(255) NOT NULL, author VARCHAR(255) NOT NULL, category VARCHAR(100), description TEXT,
 total_quantity INT NOT NULL, available_quantity INT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CHECK(total_quantity>=0), CHECK(available_quantity>=0 AND available_quantity<=total_quantity),
 INDEX(title), INDEX(author), INDEX(category)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS borrow_requests (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, user_id BIGINT UNSIGNED NOT NULL, book_id BIGINT UNSIGNED NOT NULL,
 borrow_date DATE NOT NULL, due_date DATE NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 reviewed_by BIGINT UNSIGNED NULL, reviewed_at TIMESTAMP NULL, decision_note VARCHAR(500),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(book_id) REFERENCES books(id) ON DELETE RESTRICT,
 FOREIGN KEY(reviewed_by) REFERENCES users(id) ON DELETE RESTRICT,
 CHECK(due_date>borrow_date), CHECK(status IN ('PENDING','APPROVED','DENIED')),
 INDEX(user_id,created_at), INDEX(status,created_at), INDEX(book_id,status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash CHAR(64) PRIMARY KEY, csrf_token CHAR(64) NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, INDEX(expires_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, actor_user_id BIGINT UNSIGNED NULL,
 event_type VARCHAR(100) NOT NULL, entity_type VARCHAR(50), entity_id VARCHAR(100), request_id VARCHAR(100),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor_user_id) REFERENCES users(id) ON DELETE SET NULL, INDEX(request_id), INDEX(event_type,created_at)
) ENGINE=InnoDB;
